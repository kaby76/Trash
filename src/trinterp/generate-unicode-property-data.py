#!/usr/bin/env python3
"""Extract the Unicode properties needed by Trash from antlr-ng's UnicodeData.ts.

Usage: python generate-unicode-property-data.py PATH/TO/UnicodeData.ts

The input is generated by antlr-ng/build/generate-unicode-data.ts. Its data is
used under the antlr-ng BSD 3-clause license; see UnicodePropertyData.LICENSE.
"""

import re
import sys

source = open(sys.argv[1], encoding="utf-8").read()
blocks = re.findall(
    r'set = new IntervalSet\(\);(.*?)propertyCodePointRanges\.set\("([^"]+)", set\);',
    source,
    re.S,
)
required = {
    "binary_property=id_start",
    "binary_property=id_continue",
    "binary_property=white_space",
    "binary_property=emoji",
    "binary_property=emoji_presentation",
    "binary_property=extended_pictographic",
}
required.update(
    name for _, name in blocks if name.startswith("grapheme_cluster_break=")
)
found = {}
for body, name in blocks:
    if name not in required:
        continue
    ranges = re.findall(r"set\.addRange\(0x([0-9A-F]+), 0x([0-9A-F]+)\)", body)
    found[name] = ",".join(f"{start}-{end}" for start, end in ranges)

missing = required - found.keys()
if missing:
    raise SystemExit(f"Missing Unicode properties: {sorted(missing)}")

print("# Generated from antlr-ng src/generated/UnicodeData.ts (BSD 3-clause).")
for name, ranges in sorted(found.items()):
    print(f"{name}|{ranges}")
